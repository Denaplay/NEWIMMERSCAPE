  using (public.current_staff_permission() = 'organizator');

-- Сохраняет видимость броней, созданных до появления отдельной таблицы клиентов.
insert into public.staff_clients (
  booking_id, client_name, client_phone, client_email, quest_name,
  booking_date, booking_time, comment, extra_services, created_at
)
select id, client_name, client_phone, client_email, quest_name,
       booking_date, booking_time, comment, extra_services, created_at
from public.staff_bookings
on conflict on constraint staff_clients_booking_id_key do nothing;

update public.staff_clients as client
set comment = booking.comment
from public.staff_bookings as booking
where client.booking_id = booking.id
  and client.comment = ''
  and booking.comment <> '';

create or replace function public.create_site_booking(p_booking jsonb, p_idempotency_key text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_booking_id bigint;
  supplied_user_id uuid := nullif(p_booking ->> 'user_id', '')::uuid;
begin
  if coalesce(trim(p_booking ->> 'client_name'), '') = ''
     or coalesce(trim(p_booking ->> 'client_phone'), '') = '' then
    raise exception 'Имя и телефон обязательны';
  end if;
  if supplied_user_id is not null and supplied_user_id is distinct from auth.uid() then
    raise exception 'Нельзя создать бронь от имени другого пользователя';
  end if;

  if coalesce(trim(p_idempotency_key), '') = ''
     or coalesce(trim(p_booking ->> 'quest_name'), '') = '' then
    raise exception 'Не передан идентификатор запроса или название квеста';
  end if;

  insert into public.staff_bookings (
    user_id, quest_name, booking_date, booking_time, client_name, client_phone,
    client_email, players, status, comment, extra_services, total_amount,
    source, idempotency_key
  ) values (
    supplied_user_id, trim(p_booking ->> 'quest_name'), (p_booking ->> 'booking_date')::date,
    (p_booking ->> 'booking_time')::time, trim(p_booking ->> 'client_name'),
    trim(p_booking ->> 'client_phone'), coalesce(trim(p_booking ->> 'client_email'), ''),
    greatest(coalesce((p_booking ->> 'players')::integer, 1), 1), 'new',
    coalesce(p_booking ->> 'comment', ''), coalesce(p_booking ->> 'extra_services', ''),
    coalesce(p_booking ->> 'total_amount', ''), 'site', p_idempotency_key
  )
  on conflict (idempotency_key) do update
    set idempotency_key = excluded.idempotency_key
  returning id into v_booking_id;

  insert into public.staff_clients (
    booking_id, client_name, client_phone, client_email, quest_name,
    booking_date, booking_time, comment, extra_services
  ) values (
    v_booking_id, trim(p_booking ->> 'client_name'), trim(p_booking ->> 'client_phone'),
    coalesce(trim(p_booking ->> 'client_email'), ''), trim(p_booking ->> 'quest_name'),
    (p_booking ->> 'booking_date')::date, (p_booking ->> 'booking_time')::time,
    coalesce(p_booking ->> 'comment', ''),
    coalesce(p_booking ->> 'extra_services', '')
  )
  on conflict on constraint staff_clients_booking_id_key do nothing;
  return v_booking_id;
end;
$$;
revoke all on function public.create_site_booking(jsonb, text) from public;
grant execute on function public.create_site_booking(jsonb, text) to anon, authenticated;

-- Оператор может менять только статус и сумму в поле «Оплачено».
create or replace function public.operator_update_booking(
  p_booking_id bigint,
  p_status text,
  p_paid_amount numeric
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if public.current_staff_permission() <> 'operator' then
    raise exception 'Функция доступна только оператору';
  end if;
  if p_status not in ('new', 'service', 'confirmed', 'visited', 'no_answer', 'awaiting_prepayment', 'closed') then
    raise exception 'Недопустимый статус брони';
  end if;
  if p_paid_amount < 0 then
    raise exception 'Оплаченная сумма не может быть отрицательной';
  end if;
  update public.staff_bookings
  set status = p_status, paid_amount = p_paid_amount
  where id = p_booking_id;
  if not found then raise exception 'Бронь не найдена'; end if;
end;
$$;
revoke all on function public.operator_update_booking(bigint, text, numeric) from public;
grant execute on function public.operator_update_booking(bigint, text, numeric) to authenticated;

