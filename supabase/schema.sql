create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  visits_count integer not null default 0 check (visits_count >= 0),
  permission text check (permission is null or permission in ('operator', 'manager', 'organizator')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles
  add column if not exists visits_count integer not null default 0 check (visits_count >= 0);
alter table public.profiles
  add column if not exists permission text check (permission is null or permission in ('operator', 'manager', 'organizator'));

alter table public.profiles enable row level security;

grant select on public.profiles to authenticated;
revoke update on public.profiles from authenticated;
grant update (full_name) on public.profiles to authenticated;
revoke delete on public.profiles from authenticated;

create or replace function public.current_staff_permission()
returns text language sql stable security definer set search_path = ''
as $$ select permission from public.profiles where id = auth.uid() $$;

